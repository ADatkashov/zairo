/// Icon size scale, deliberately built from the same steps as
/// [FactorySpacing] (16/20/24/32/40) so an icon and the gap next to it
/// always come from one rhythm instead of two unrelated scales.
class FactoryIconSize {
  const FactoryIconSize._();

  static const double xs = 16;
  static const double sm = 20;
  static const double md = 24;
  static const double lg = 32;
  static const double xl = 40;
}
